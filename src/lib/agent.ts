import { createHash, timingSafeEqual } from "node:crypto";
import type { NextRequest } from "next/server";
import { HttpError } from "@/lib/auth/server";
import { bundle, fileUrl, plain, type ThreadBundle } from "@/lib/export";
import { isDevComment } from "@/lib/figma/dev";
import type { Comment, Folder, Review } from "@/lib/types";
import { viewportExportLabel, viewportRange } from "@/lib/viewports";

/**
 * Read-only access for a coding agent (or any script) from the command line.
 *
 * Off unless both variables are set:
 *   REDLINE_AGENT_TOKEN    shared secret, at least 32 characters
 *   REDLINE_AGENT_PROJECT  the one project the token may read
 *
 * Callers send `Authorization: Bearer <token>`. The token is not a user: it
 * cannot write, and it sees nothing outside that project. See docs/agent-api.md.
 */

const MIN_TOKEN_LENGTH = 32;

const digest = (s: string) => createHash("sha256").update(s).digest();

/** The project this request may read; throws 404 when the API is off, 401 on a bad token. */
export function agentProject(req: NextRequest): string {
  const token = process.env.REDLINE_AGENT_TOKEN?.trim();
  const project = process.env.REDLINE_AGENT_PROJECT?.trim();
  if (!token || token.length < MIN_TOKEN_LENGTH || !project) throw new HttpError(404, "Not found.");
  const sent = req.headers.get("authorization")?.match(/^Bearer\s+(.+)$/i)?.[1]?.trim() ?? "";
  // compare fixed-length hashes so neither length nor content leaks through timing
  if (!timingSafeEqual(digest(sent), digest(token))) throw new HttpError(401, "Invalid or missing token.");
  return project;
}

export function requestOrigin(req: NextRequest): string {
  const host = req.headers.get("x-forwarded-host") || req.headers.get("host") || req.nextUrl.host;
  const proto = req.headers.get("x-forwarded-proto") || (host.startsWith("localhost") ? "http" : "https");
  return `${proto}://${host}`;
}

export const NO_STORE = { "cache-control": "no-store" };

/* ─── the thread shape an agent reads ─────────────────────────────────────── */

export interface AgentFile {
  name: string;
  kind: "image" | "video";
  url: string;
  width?: number;
  height?: number;
  duration_s?: number;
}

export interface AgentThread {
  id: string;
  status: "open" | "resolved";
  /** "figma-diff" = generated by Compare with Figma; "comment" = written by a person */
  kind: "comment" | "figma-diff";
  title: string | null;
  body: string;
  author: string;
  created_at: string;
  edited_at: string | null;
  link: string;
  page: { review_id: string; title: string; url: string; mode: Review["mode"]; folder: string | null; link: string };
  viewport: { written_at: number; applies_to: string; range: { min: number; max: number } | null };
  element: { label: string | null; selector: string | null } | null;
  /** where the pin sits: fraction of the element box, and absolute page coordinates */
  position: { fx: number; fy: number; page_x: number; page_y: number } | null;
  region: { x: number; y: number; w: number; h: number } | null;
  figma: { rule: string; severity: string; layer: string; expected: string; actual: string; figma_url: string } | null;
  reactions: Record<string, string[]>;
  attachments: AgentFile[];
  replies: { id: string; author: string; body: string; created_at: string; attachments: AgentFile[] }[];
}

function files(origin: string, c: Comment): AgentFile[] {
  return (c.attachments || []).map((a) => ({
    name: a.name,
    kind: a.kind === "video" ? "video" : "image",
    url: fileUrl(origin, c, a),
    ...(a.w ? { width: a.w } : {}),
    ...(a.h ? { height: a.h } : {}),
    ...(a.duration ? { duration_s: a.duration } : {}),
  }));
}

export function toAgentThread(origin: string, review: Review, folders: Map<string, Folder>, { root, replies }: ThreadBundle): AgentThread {
  const a = root.anchor;
  return {
    id: root.id,
    status: root.resolved ? "resolved" : "open",
    kind: isDevComment(root) ? "figma-diff" : "comment",
    title: root.title,
    body: plain(root.body),
    author: root.author_name,
    created_at: root.created_at,
    edited_at: root.edited_at,
    link: `${origin}/r/${review.id}?c=${root.id}`,
    page: {
      review_id: review.id,
      title: review.title,
      url: review.url,
      mode: review.mode,
      folder: (review.folder_id && folders.get(review.folder_id)?.name) || null,
      link: `${origin}/r/${review.id}`,
    },
    viewport: { written_at: root.viewport_width, applies_to: viewportExportLabel(root), range: viewportRange(root) },
    element: a && (a.selector || a.element_label) ? { label: a.element_label ?? null, selector: a.selector } : null,
    position: a ? { fx: a.fx, fy: a.fy, page_x: a.px, page_y: a.py } : null,
    region: a?.region ?? null,
    figma: a?.dev
      ? { rule: a.dev.rule, severity: a.dev.severity, layer: a.dev.figmaName, expected: a.dev.expected, actual: a.dev.actual, figma_url: a.dev.figmaUrl }
      : null,
    reactions: root.reactions || {},
    attachments: files(origin, root),
    replies: replies.map((r) => ({ id: r.id, author: r.author_name, body: plain(r.body), created_at: r.created_at, attachments: files(origin, r) })),
  };
}

/** Every thread of the given reviews, oldest first, as the agent sees them. */
export function agentThreads(origin: string, reviews: { review: Review; comments: Comment[] }[], folders: Folder[]): AgentThread[] {
  const byId = new Map(folders.map((f) => [f.id, f]));
  return reviews
    .flatMap(({ review, comments }) => bundle(comments).map((t) => toAgentThread(origin, review, byId, t)))
    .sort((x, y) => x.created_at.localeCompare(y.created_at));
}
